const I18n = {
  current: 'ko',

  init() {
    const saved = localStorage.getItem('alfred-lang');
    const browser = (navigator.language || 'ko').toLowerCase().startsWith('en') ? 'en' : 'ko';
    this.current = saved || browser;
    this.apply(this.current);
    this.bindToggle();
  },

  apply(lang) {
    if (!translations[lang]) return;
    this.current = lang;
    document.documentElement.lang = lang;
    localStorage.setItem('alfred-lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = translations[lang][key];
      if (val === undefined) return;

      if (el.tagName === 'TITLE') {
        el.textContent = val;
      } else if (el.tagName === 'META') {
        el.setAttribute('content', val);
      } else {
        el.innerHTML = val;
      }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });
  },

  bindToggle() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        this.apply(btn.dataset.lang);
      });
    });
  }
};

document.addEventListener('DOMContentLoaded', () => I18n.init());
